/* ---------------- SSD1306 上电命令序列（页寻址） ---------------- */
static const uint8_t s_oled_init_cmds[] = {
    OLED_CTRL_CMD,
    0xAE,             /* 显示关 */
    0xD5, 0x80,       /* 时钟分频/振荡频率 */
    0xA8, 0x3F,       /* 复用比 1/64 */
    0xD3, 0x00,       /* 显示偏移 0 */
    0x40,             /* 显示起始行 0 */
    0x8D, 0x14,       /* 电荷泵使能 */
    0x20, 0x02,       /* 寻址模式：页寻址 */
    0xA1,             /* 段重映射（左右） */
    0xC8,             /* COM 扫描方向（上下） */
    0xDA, 0x12,       /* COM 引脚配置（128x64） */
    0x81, 0xCF,       /* 对比度 */
    0xD9, 0xF1,       /* 预充电周期 */
    0xDB, 0x40,       /* VCOM 电压 */
    0xA4,             /* 显示内容跟随 GDDRAM */
    0xA6,             /* 正常显示（非反色） */
    0xAF,             /* 显示开 */
};

/* 显存写入缓冲：1 控制字节 + 128 数据字节 */
static uint8_t s_xfer_buf[1u + OLED_PAGE_BYTES];

static uint8_t oled_font_index(char ch);
static int32_t oled_set_pos(uint8_t col, uint8_t page);

int32_t driver_oled_init(void)
{
    static const i2c_port_cfg_t cfg = { 400000u, 1u }; /* 400kHz，启用内部上拉 */
    int32_t r = i2c_port_init(I2C_PORT_OLED, &cfg);
    if (r != PORT_OK) { return r; }
    r = i2c_port_write_raw(I2C_PORT_OLED, OLED_DEV_ADDR,
                           s_oled_init_cmds, sizeof(s_oled_init_cmds));
    if (r != PORT_OK) { return r; }
    return driver_oled_clear();
}

int32_t driver_oled_clear(void)
{
    int32_t r;
    uint8_t page;

    memset(s_xfer_buf, 0, sizeof(s_xfer_buf));
    s_xfer_buf[0] = OLED_CTRL_DATA;
    for (page = 0; page < OLED_PAGE_COUNT; page++) {
        r = oled_set_pos(0u, page);
        if (r != PORT_OK) { return r; }
        r = i2c_port_write_raw(I2C_PORT_OLED, OLED_DEV_ADDR,
                               s_xfer_buf, sizeof(s_xfer_buf));
        if (r != PORT_OK) { return r; }
    }
    return PORT_OK;
}

int32_t driver_oled_show_line(uint8_t line, const char *text)
{
    const uint8_t *glyph;
    uint16_t t;
    uint8_t col;
    int32_t r;
    char ch;

    if ((line >= DRIVER_OLED_LINES) || (text == 0)) {
        return PORT_ERR_PARAM;
    }

    /* 上半页：行内 16 字符的字形前 8 字节连写（页内列地址自动递增） */
    s_xfer_buf[0] = OLED_CTRL_DATA;
    for (col = 0; col < DRIVER_OLED_LINE_CHARS; col++) {
        ch = (char)0;
        /* 逐字符取值（text 长度可能小于 16，尾部补空格） */
        {
            const char *p = text;
            uint8_t n = col;
            while ((n > 0u) && (*p != (char)0)) { p++; n--; }
            if (n == 0u) { ch = *p; }
        }
        glyph = s_oled_font[oled_font_index(ch)];
        for (t = 0; t < 8u; t++) {
            s_xfer_buf[1u + (uint16_t)col * 8u + t] = glyph[t];
        }
    }
    r = oled_set_pos(0u, (uint8_t)(line * 2u));
    if (r != PORT_OK) { return r; }
    r = i2c_port_write_raw(I2C_PORT_OLED, OLED_DEV_ADDR,
                           s_xfer_buf, sizeof(s_xfer_buf));
    if (r != PORT_OK) { return r; }

    /* 下半页：各字符字形后 8 字节 */
    for (col = 0; col < DRIVER_OLED_LINE_CHARS; col++) {
        ch = (char)0;
        {
            const char *p = text;
            uint8_t n = col;
            while ((n > 0u) && (*p != (char)0)) { p++; n--; }
            if (n == 0u) { ch = *p; }
        }
        glyph = s_oled_font[oled_font_index(ch)];
        for (t = 0; t < 8u; t++) {
            s_xfer_buf[1u + (uint16_t)col * 8u + t] = glyph[8u + t];
        }
    }
    r = oled_set_pos(0u, (uint8_t)(line * 2u + 1u));
    if (r != PORT_OK) { return r; }
    return i2c_port_write_raw(I2C_PORT_OLED, OLED_DEV_ADDR,
                              s_xfer_buf, sizeof(s_xfer_buf));
}

int32_t driver_oled_deinit(void)
{
    static const uint8_t disp_off[2] = { OLED_CTRL_CMD, 0xAE };
    (void)i2c_port_write_raw(I2C_PORT_OLED, OLED_DEV_ADDR,
                             disp_off, sizeof(disp_off));
    return i2c_port_deinit(I2C_PORT_OLED);
}

/** 字符集查找：未收录字符回落为空格。 */
static uint8_t oled_font_index(char ch)
{
    const char *hit;
    if (ch == (char)0) {
        return 0u; /* 字符串结束后的填充位 = 空格 */
    }
    hit = strchr(s_oled_font_chars, ch);
    if ((hit == 0) || (*hit == (char)0)) {
        return 0u;
    }
    return (uint8_t)(hit - s_oled_font_chars);
}

/** 设置页寻址写入位置：列 0 + 指定页。 */
static int32_t oled_set_pos(uint8_t col, uint8_t page)
{
    uint8_t cmd[5];
    cmd[0] = OLED_CTRL_CMD;
    cmd[1] = 0x10u | (uint8_t)((col >> 4) & 0x0Fu); /* 高列地址 */
    cmd[2] = 0x00u | (uint8_t)(col & 0x0Fu);        /* 低列地址 */
    cmd[3] = OLED_CTRL_CMD;
    cmd[4] = 0xB0u | (page & 0x07u);                /* 页地址 */
    return i2c_port_write_raw(I2C_PORT_OLED, OLED_DEV_ADDR, cmd, 5u);
}
