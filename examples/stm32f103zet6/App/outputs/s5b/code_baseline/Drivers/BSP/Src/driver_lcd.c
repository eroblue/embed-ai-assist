/* 字符单元像素缓冲（16x32 = 512 像素；clear 时复用为行缓冲） */
static uint16_t s_cell_buf[LCD_CHAR_W * LCD_CHAR_H];

static uint8_t lcd_font_index(char ch);
static uint8_t lcd_glyph_bit(const uint8_t *glyph, uint8_t row, uint8_t col);
static int32_t lcd_set_window(uint16_t x0, uint16_t y0, uint16_t x1, uint16_t y1);

int32_t driver_lcd_init(void)
{
    int32_t r;
    uint16_t i;
    uint8_t k;

    r = par_port_init(PAR_PORT_LCD);
    if (r != PORT_OK) { return r; }

    /* 退出睡眠 + 等待（数据手册典型 120ms） */
    r = par_port_write_cmd(PAR_PORT_LCD, LCD_CMD_SLPOUT);
    if (r != PORT_OK) { return r; }
    (void)timer_port_delay_us(120000u);

    for (i = 0; i < (uint16_t)(sizeof(s_lcd_init_seq) / sizeof(s_lcd_init_seq[0])); i++) {
        r = par_port_write_cmd(PAR_PORT_LCD, s_lcd_init_seq[i].cmd);
        if (r != PORT_OK) { return r; }
        for (k = 0; k < s_lcd_init_seq[i].nparams; k++) {
            r = par_port_write_data(PAR_PORT_LCD, s_lcd_init_seq[i].params[k]);
            if (r != PORT_OK) { return r; }
        }
    }

    /* 开显示 + 等待 20ms 后清屏 */
    r = par_port_write_cmd(PAR_PORT_LCD, LCD_CMD_DISPON);
    if (r != PORT_OK) { return r; }
    (void)timer_port_delay_us(20000u);

    return driver_lcd_clear();
}

int32_t driver_lcd_clear(void)
{
    int32_t r;
    uint16_t y;

    r = lcd_set_window(0u, 0u, (uint16_t)(LCD_WIDTH - 1u), (uint16_t)(LCD_HEIGHT - 1u));
    if (r != PORT_OK) { return r; }

    /* 复用单元缓冲作行缓冲（512 >= 240） */
    for (y = 0; y < LCD_WIDTH; y++) {
        s_cell_buf[y] = LCD_COLOR_BG;
    }
    for (y = 0; y < LCD_HEIGHT; y++) {
        r = par_port_write_data_block(PAR_PORT_LCD, s_cell_buf, LCD_WIDTH);
        if (r != PORT_OK) { return r; }
    }
    return PORT_OK;
}

int32_t driver_lcd_show_line(uint8_t line, const char *text)
{
    int32_t r;
    uint8_t col;
    uint16_t y0;

    if ((line >= DRIVER_LCD_LINES) || (text == 0)) {
        return PORT_ERR_PARAM;
    }
    y0 = (uint16_t)line * LCD_CHAR_H;

    /* 逐字符渲染整行（文本不足 15 列时以空格补齐；'\0' 之后按空格处理） */
    for (col = 0; col < DRIVER_LCD_LINE_CHARS; col++) {
        char ch = *text;
        const uint8_t *glyph;
        uint16_t idx = 0;
        uint8_t cr;

        if (ch != (char)0) {
            text++;
        }
        glyph = s_lcd_font[lcd_font_index(ch)];

        /* 8x16 字模 2 倍放大填充 16x32 单元（每字形行重复两次、每字形列重复两次） */
        for (cr = 0; cr < LCD_CHAR_H; cr++) {
            uint8_t gr = (uint8_t)(cr >> 1);   /* 字形行 0..15 */
            uint8_t gc;
            for (gc = 0; gc < 8u; gc++) {
                uint16_t px = lcd_glyph_bit(glyph, gr, gc) ? LCD_COLOR_FG : LCD_COLOR_BG;
                s_cell_buf[idx++] = px;
                s_cell_buf[idx++] = px;        /* 水平 x2 */
            }
        }

        r = lcd_set_window((uint16_t)col * LCD_CHAR_W, y0,
                           (uint16_t)(col * LCD_CHAR_W + LCD_CHAR_W - 1u),
                           (uint16_t)(y0 + LCD_CHAR_H - 1u));
        if (r != PORT_OK) { return r; }
        r = par_port_write_data_block(PAR_PORT_LCD, s_cell_buf,
                                      (uint32_t)(LCD_CHAR_W * LCD_CHAR_H));
        if (r != PORT_OK) { return r; }
    }
    return PORT_OK;
}

int32_t driver_lcd_deinit(void)
{
    (void)par_port_write_cmd(PAR_PORT_LCD, LCD_CMD_DISPOFF);
    return par_port_deinit(PAR_PORT_LCD);
}

/** 字符集查找：未收录字符回落为空格。 */
static uint8_t lcd_font_index(char ch)
{
    const char *hit;
    if (ch == (char)0) {
        return 0u; /* 字符串结束后的填充位 = 空格 */
    }
    hit = strchr(s_lcd_font_chars, ch);
    if ((hit == 0) || (*hit == (char)0)) {
        return 0u;
    }
    return (uint8_t)(hit - s_lcd_font_chars);
}

/** 页分块字模取位：[col]=上页列（行0-7），[8+col]=下页列（行8-15），bit0=最上行。 */
static uint8_t lcd_glyph_bit(const uint8_t *glyph, uint8_t row, uint8_t col)
{
    if (row < 8u) {
        return (uint8_t)((glyph[col] >> row) & 1u);
    }
    return (uint8_t)((glyph[8u + col] >> (row - 8u)) & 1u);
}

/** 设置写入窗口：CASET（列）+ PASET（行）+ RAMWR。 */
static int32_t lcd_set_window(uint16_t x0, uint16_t y0, uint16_t x1, uint16_t y1)
{
    int32_t r;

    r = par_port_write_cmd(PAR_PORT_LCD, LCD_CMD_CASET);
    if (r != PORT_OK) { return r; }
    r = par_port_write_data(PAR_PORT_LCD, (uint16_t)(x0 >> 8));
    if (r != PORT_OK) { return r; }
    r = par_port_write_data(PAR_PORT_LCD, (uint16_t)(x0 & 0xFFu));
    if (r != PORT_OK) { return r; }
    r = par_port_write_data(PAR_PORT_LCD, (uint16_t)(x1 >> 8));
    if (r != PORT_OK) { return r; }
    r = par_port_write_data(PAR_PORT_LCD, (uint16_t)(x1 & 0xFFu));
    if (r != PORT_OK) { return r; }

    r = par_port_write_cmd(PAR_PORT_LCD, LCD_CMD_PASET);
    if (r != PORT_OK) { return r; }
    r = par_port_write_data(PAR_PORT_LCD, (uint16_t)(y0 >> 8));
    if (r != PORT_OK) { return r; }
    r = par_port_write_data(PAR_PORT_LCD, (uint16_t)(y0 & 0xFFu));
    if (r != PORT_OK) { return r; }
    r = par_port_write_data(PAR_PORT_LCD, (uint16_t)(y1 >> 8));
    if (r != PORT_OK) { return r; }
    r = par_port_write_data(PAR_PORT_LCD, (uint16_t)(y1 & 0xFFu));
    if (r != PORT_OK) { return r; }

    return par_port_write_cmd(PAR_PORT_LCD, LCD_CMD_RAMWR);
}
