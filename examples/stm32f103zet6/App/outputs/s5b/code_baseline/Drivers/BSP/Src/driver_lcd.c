/* ---------------- ILI9341 上电寄存器序列（SLPOUT 之后发送） ---------------- */
typedef struct {
    uint8_t cmd;             /* 命令字 */
    uint8_t nparams;         /* 参数字节数 */
    uint8_t params[15];      /* 参数（低 8 位有效） */
} lcd_reg_t;

