#!/usr/bin/env python
"""S7b 阶段 A'：Makefile 自动生成分支（仅显式 build_system=gcc_make 且无 Makefile 时）。

生成策略（优先级从高到低）：
  1. 解析工程内已有 .uvprojx（单一事实来源：defines / include paths / 源文件清单 /
     CPU 型号 / IROM-IRAM 内存布局）
  2. 目录扫描 + 平台惯例（无 uvprojx 时的 fallback）

产物（写入目标工程根）：
  - Makefile（带 "# Generated by S7b build" 标记，skip-if-modified）
  - 链接脚本：工程内用户自维护 .ld > 平台库 linker_scripts/*.ld（零偏移时直接用；
    引用平台脚本会顺带清理被取代的旧生成脚本）> 从内存布局生成最小可用脚本
    （flash_offset > 0 时必定生成，因平台脚本为固定基址、需偏移后布局）

启动文件：Keil 的 .s 为 ARMCC 语法（AREA/DCD/PROC），GCC 无法汇编——自动替换为
平台库 platforms/<platform>/sdk/startup/gcc_ride7/（GNU 语法）下的同名文件。

本模块不修改任何其他文件（.uvprojx / .ewp / CMakeLists.txt 均只读）。
"""

from __future__ import annotations

import re
import xml.etree.ElementTree as ET
from pathlib import Path

GENERATED_MARKER = "# Generated by S7b build"

# 扫描 fallback 的平台惯例（mcu_family → cortex 核 + 内存布局）。
# uvprojx 轨不走此表（内存与 CPU 从 <Cpu> 行解析）。
PLATFORM_FALLBACK = {
    "STM32F1": {"cpu": "cortex-m3", "irom": (0x08000000, 0x80000),
                "iram": (0x20000000, 0x10000)},
    "GD32F2": {"cpu": "cortex-m3", "irom": (0x08000000, 0x80000),
               "iram": (0x20000000, 0x18000)},
}

# 目录扫描 fallback 时排除的目录（与 S7b 推断扫描 + IDE 目录约定一致）
SCAN_EXCLUDE = {"outputs", "build", "mdk-arm", "iar", "objects", "listings",
                ".history", "rte", "debugconfig"}

# 工程文件发现（uvprojx/.ld）时排除的目录——比 SCAN_EXCLUDE 宽松：
# IDE 目录（MDK-ARM 等）正是 uvprojx 的约定位置，不可排除
PROJECT_DISCOVER_EXCLUDE = {"outputs", "build", "objects", "listings",
                            ".history", "rte", "debugconfig"}


class MakefileGenError(Exception):
    """生成失败（源为空 / CPU 信息无法推导 / 链接脚本无从生成）。"""


def _rel_posix(path: Path, target_root: Path) -> str:
    """转 target_root 相对 POSIX 路径（含盘符差异时返回绝对 POSIX 路径）。"""
    try:
        return path.resolve().relative_to(target_root.resolve()).as_posix()
    except ValueError:
        return path.resolve().as_posix().replace("\\", "/")


# ---------------- uvprojx 解析（策略 1） ----------------

_CPU_RE = re.compile(r'CPUTYPE\("([^"]+)"\)')
_IROM_RE = re.compile(r"IROM\(0x([0-9A-Fa-f]+),0x([0-9A-Fa-f]+)\)")
_IRAM_RE = re.compile(r"IRAM\(0x([0-9A-Fa-f]+),0x([0-9A-Fa-f]+)\)")


def parse_uvprojx(uvprojx: Path, target_root: Path) -> dict:
    """解析 uvprojx 提取编译所需信息（只读）。

    返回 {target, cpu, defines, includes, c_sources, keil_startup, irom, iram}。
    """
    try:
        tree = ET.parse(uvprojx)
    except ET.ParseError as exc:
        raise MakefileGenError(f"uvprojx 解析失败（XML 非法）: {uvprojx} ({exc})") from exc
    root = tree.getroot()

    target_name = ""
    cpu = ""
    irom = iram = None
    defines: list[str] = []
    includes: list[str] = []
    c_sources: list[str] = []
    keil_startup: str | None = None

    tname = root.findtext(".//TargetName")
    if tname:
        target_name = tname.strip()
    cpu_text = root.findtext(".//Cpu") or ""
    m = _CPU_RE.search(cpu_text)
    if m:
        cpu = m.group(1).lower()
    m = _IROM_RE.search(cpu_text)
    if m:
        irom = (int(m.group(1), 16), int(m.group(2), 16))
    m = _IRAM_RE.search(cpu_text)
    if m:
        iram = (int(m.group(1), 16), int(m.group(2), 16))

    # 只取第一个 Target 的 Cads 配置（多 target 工程本就要求显式 build_config）
    for vc in root.iter("VariousControls"):
        for d in (vc.findtext("Define") or "").split(","):
            d = d.strip()
            if d:
                defines.append(d)
        for inc in (vc.findtext("IncludePath") or "").split(";"):
            inc = inc.strip()
            if inc:
                p = Path(inc)
                if not p.is_absolute():
                    p = uvprojx.parent / p
                includes.append(_rel_posix(p, target_root))
        break  # 第一个 VariousControls（C 级配置）

    for fp in root.iter("FilePath"):
        f = (fp.text or "").strip()
        if not f:
            continue
        p = Path(f)
        if not p.is_absolute():
            p = uvprojx.parent / p
        rel = _rel_posix(p, target_root)
        low = p.suffix.lower()
        if low == ".c":
            c_sources.append(rel)
        elif low in (".s", ".a51", ".asm"):
            if rel != keil_startup:  # 只记录一个 Keil 启动文件（ARMCC 语法，需替换）
                keil_startup = rel if keil_startup is None else keil_startup

    return {"target": target_name, "cpu": cpu, "defines": defines,
            "includes": includes, "c_sources": c_sources,
            "keil_startup": keil_startup, "irom": irom, "iram": iram}


# ---------------- 目录扫描 fallback（策略 2） ----------------

def scan_sources(target_root: Path, mcu_family: str) -> dict:
    """按目录约定递归收集源文件 + 平台惯例推导 CPU/内存。"""
    plat = PLATFORM_FALLBACK.get(mcu_family or "")
    if not plat:
        raise MakefileGenError(
            f"无 uvprojx 可解析，且平台 {mcu_family or '(未知)'} 不在扫描 fallback 惯例表"
            "（PLATFORM_FALLBACK）——请手写 Makefile 或改用 keil/iar")
    c_sources: list[str] = []
    for entry in sorted(target_root.rglob("*.c")):
        parts = {p.lower() for p in entry.relative_to(target_root).parts[:-1]}
        if parts & SCAN_EXCLUDE:
            continue
        c_sources.append(entry.relative_to(target_root).as_posix())
    if not c_sources:
        raise MakefileGenError(
            f"目标工程根未扫描到任何 .c 源文件（{target_root}）——S5 产物是否就位？")
    return {"target": target_root.name, "cpu": plat["cpu"], "defines": [],
            "includes": [], "c_sources": c_sources,
            "keil_startup": None, "irom": plat["irom"], "iram": plat["iram"]}


# ---------------- GCC 启动文件定位 ----------------

def find_gcc_startup(platform_dir: Path | None, keil_startup: str | None) -> Path | None:
    """定位 GNU 语法启动文件：优先 gcc_ride7 下与 Keil 启动同名的 .s。"""
    if platform_dir is None:
        return None
    startup_dir = platform_dir / "sdk" / "startup"
    if not startup_dir.is_dir():
        return None
    if keil_startup:
        name = Path(keil_startup).name
        for sub in ("gcc_ride7", "gcc", "."):
            cand = startup_dir / sub / name
            if cand.is_file():
                return cand
    # 无同名匹配：gcc* 子目录下唯一 .s 也接受
    for sub in startup_dir.iterdir():
        if sub.is_dir() and sub.name.lower().startswith("gcc"):
            s_files = sorted(sub.glob("*.s"))
            if len(s_files) == 1:
                return s_files[0]
    return None


# ---------------- .ld 生成 ----------------

def _fmt_size(n: int) -> str:
    return f"{n // 1024}K" if n % 1024 == 0 else f"{n}"


def render_linker_script(target: str, cpu: str, irom: tuple[int, int],
                         iram: tuple[int, int]) -> str:
    """最小可用 Cortex-M 链接脚本（符号约定与 ST GCC 启动文件对齐：
    _estack/_sidata/_sdata/_edata/_sbss/_ebss，.isr_vector 段）。"""
    return f"""/* {GENERATED_MARKER}（阶段 A'：无现成链接脚本时按内存布局生成） */
/* target: {target}  cpu: {cpu} */
/* FLASH: 0x{irom[0]:08X} +{_fmt_size(irom[1])}  RAM: 0x{iram[0]:08X} +{_fmt_size(iram[1])} */
ENTRY(Reset_Handler)

_Min_Heap_Size  = 0x200;   /* 512B 堆（malloc 用；纯裸机可改 0） */
_Min_Stack_Size = 0x400;   /* 1KB 栈 */

MEMORY
{{
  FLASH (rx)  : ORIGIN = 0x{irom[0]:08X}, LENGTH = {_fmt_size(irom[1])}
  RAM   (rwx) : ORIGIN = 0x{iram[0]:08X}, LENGTH = {_fmt_size(iram[1])}
}}

_estack = ORIGIN(RAM) + LENGTH(RAM);    /* 栈顶 = RAM 末尾（Cortex-M 满递减栈） */

SECTIONS
{{
  .isr_vector :
  {{
    . = ALIGN(4);
    KEEP(*(.isr_vector))
    . = ALIGN(4);
  }} > FLASH

  .text :
  {{
    . = ALIGN(4);
    *(.text*)
    *(.rodata*)
    KEEP(*(.init))
    KEEP(*(.fini))
    . = ALIGN(4);
    _etext = .;
  }} > FLASH

  .ARM.extab   : {{ *(.ARM.extab* .gnu.linkonce.armextab.*) }} > FLASH
  .ARM.exidx   : {{ __exidx_start = .; *(.ARM.exidx*) __exidx_end = .; }} > FLASH

  /* .data 初值在 FLASH，启动时由 Reset_Handler 拷贝到 RAM */
  _sidata = LOADADDR(.data);
  .data :
  {{
    . = ALIGN(4);
    _sdata = .;
    *(.data*)
    . = ALIGN(4);
    _edata = .;
  }} > RAM AT > FLASH

  .bss (NOLOAD) :
  {{
    . = ALIGN(4);
    _sbss = .;
    *(.bss*)
    *(COMMON)
    . = ALIGN(4);
    _ebss = .;
  }} > RAM

  ._user_heap_stack (NOLOAD) :
  {{
    . = ALIGN(8);
    PROVIDE(end = .);
    . = . + _Min_Heap_Size + _Min_Stack_Size;
    . = ALIGN(8);
  }} > RAM

  /DISCARD/ : {{ *(.comment) }}
}}
"""


# ---------------- Makefile 渲染 ----------------

def render_makefile(target: str, cpu: str, defines: list[str], includes: list[str],
                    c_sources: list[str], gcc_startup: Path | None,
                    ld_rel: str, source_basis: str) -> str:
    """渲染 GNU Make Makefile（输出 build/<target>.elf/.hex/.bin，POSIX recipe）。"""
    defs = " ".join(f"-D{d}" for d in defines) if defines else ""
    incs = " ".join(f"-I{d}" for d in includes) if includes else ""

    # SRC：工程内 .c（相对路径）+ GNU 启动文件（平台库绝对路径），反斜杠续行
    src_items = list(c_sources)
    startup_note = ""
    if gcc_startup is not None:
        src_items.append(gcc_startup.as_posix())
        startup_note = (f"\n# 最后一项为 GNU 语法启动文件（平台库；Keil .s 为 ARMCC 语法不可用）"
                        f": {gcc_startup.name}")
    src_block = (" \\\n".join(f"  {s}" for s in src_items)) if src_items else "  #（空）"

    # vpath：让 build/%.o 模式规则在源文件所在目录中查找
    vpath_c = " ".join(sorted({Path(s).parent.as_posix()
                               for s in c_sources if Path(s).parent.as_posix() != "."}))
    vpath_s = (gcc_startup.parent.as_posix()
               if gcc_startup is not None else "")

    return f"""{GENERATED_MARKER}（阶段 A' Makefile 自动生成分支）
# 数据来源: {source_basis} | 输出: build/{target}.elf/.hex/.bin
# skip-if-modified：本文件含上方生成标记，用户修改后 S7b 不再覆盖；删除本文件即恢复自动生成

TARGET  := {target}
BUILD   := build
PREFIX  := arm-none-eabi-
CC      := $(PREFIX)gcc
OBJCOPY := $(PREFIX)objcopy
SIZE    := $(PREFIX)size

CPU     := -mcpu={cpu} -mthumb
DEFS    := {defs}
INCLUDES:= {incs}
CFLAGS  := $(CPU) $(DEFS) $(INCLUDES) -O0 -g3 -ffunction-sections -fdata-sections -fno-common -Wall
ASFLAGS := $(CPU) -x assembler-with-cpp
LDFLAGS := $(CPU) -T{ld_rel} -Wl,--gc-sections -Wl,-Map=$(BUILD)/$(TARGET).map \\
           --specs=nano.specs --specs=nosys.specs -Wl,--start-group -lc -lm -Wl,--end-group
{startup_note}
# 源文件（.c 相对工程根；启动文件为平台库绝对路径）
SRC := {src_block}

# vpath：让 build/%.o 模式规则在下列目录中查找源文件
vpath %.c {vpath_c}
{f"vpath %.s {vpath_s}" if vpath_s else ""}

OBJS := $(addprefix $(BUILD)/, \\
  $(notdir $(patsubst %.c,%.o,$(filter %.c,$(SRC)))) \\
  $(notdir $(patsubst %.s,%.o,$(filter %.s,$(SRC)))))

.PHONY: all clean elf hex bin

all: elf bin hex

elf: $(BUILD)/$(TARGET).elf

$(BUILD)/$(TARGET).elf: $(OBJS) {ld_rel}
\t$(CC) $(OBJS) $(LDFLAGS) -o $@
\t$(SIZE) $@

$(BUILD)/%.o: %.c
\t@mkdir -p $(BUILD)
\t$(CC) $(CFLAGS) -c $< -o $@

$(BUILD)/%.o: %.s
\t@mkdir -p $(BUILD)
\t$(CC) $(ASFLAGS) -c $< -o $@

bin: $(BUILD)/$(TARGET).bin

$(BUILD)/$(TARGET).bin: $(BUILD)/$(TARGET).elf
\t$(OBJCOPY) -O binary $< $@

hex: $(BUILD)/$(TARGET).hex

$(BUILD)/$(TARGET).hex: $(BUILD)/$(TARGET).elf
\t$(OBJCOPY) -O ihex $< $@

clean:
\trm -rf $(BUILD)
"""


# ---------------- 主入口 ----------------

def generate_build_files(target_root: Path, platform_dir: Path | None,
                         mcu_family: str, build_config: str | None,
                         ide_project: Path | None,
                         flash_offset: int = 0) -> dict:
    """生成 Makefile + 链接脚本（skip-if-modified）。

    flash_offset（config project.flash_offset，OTA App 偏移）> 0 时：
    链接脚本 ORIGIN = Flash 基址 + 偏移、LENGTH = 总容量 - 偏移
    （基址/容量来自 uvprojx IROM 或 PLATFORM_FALLBACK）。

    返回 {makefile_generated, linker_script_generated, target, warnings, sources}。
    抛 MakefileGenError：源为空 / CPU 无法推导 / 链接脚本无从生成 / 偏移非法。
    """
    warnings: list[str] = []

    # ---- 信息来源（策略 1：uvprojx；策略 2：目录扫描） ----
    uvprojx: Path | None = None
    if ide_project is not None and ide_project.suffix.lower() == ".uvprojx" \
            and ide_project.is_file():
        uvprojx = ide_project
    else:
        for p in sorted(target_root.rglob("*.uvprojx")):
            if not ({q.lower() for q in p.relative_to(target_root).parts[:-1]}
                    & PROJECT_DISCOVER_EXCLUDE):
                uvprojx = p
                break
    if uvprojx is not None:
        info = parse_uvprojx(uvprojx, target_root)
        source_basis = f"uvprojx 解析（{uvprojx.relative_to(target_root).as_posix() if _contains(target_root, uvprojx) else uvprojx}）"
    else:
        info = scan_sources(target_root, mcu_family)
        source_basis = "目录扫描 + 平台惯例（PLATFORM_FALLBACK）"

    target = build_config or info["target"] or target_root.name
    cpu = info["cpu"]
    if not cpu:
        raise MakefileGenError(
            "CPU 型号无法推导（uvprojx <Cpu> 行无 CPUTYPE，且无平台惯例）"
            "——请手写 Makefile 或改用 keil/iar")
    irom, iram = info["irom"], info["iram"]
    if not irom or not iram:
        raise MakefileGenError(
            "FLASH/RAM 内存布局无法推导——请手写 Makefile 或改用 keil/iar")

    # ---- flash_offset 应用（OTA App：偏移为 config 显式值，权威来源） ----
    if flash_offset:
        if flash_offset >= irom[1]:
            raise MakefileGenError(
                f"project.flash_offset=0x{flash_offset:X} 不小于 Flash 容量 "
                f"0x{irom[1]:X}——请检查配置")
        if flash_offset % 0x200 != 0:
            warnings.append(f"flash_offset=0x{flash_offset:X} 非 512 字节对齐——"
                            "Cortex-M VTOR 通常要求向量表 512 字节对齐（M3）或 128 字节（M4），"
                            "未对齐将导致中断异常")
        # 双重偏移检测：uvprojx IROM 起址已偏离平台基址时提示（可能工程里已含 OTA 布局）
        plat = PLATFORM_FALLBACK.get(mcu_family or "")
        if plat and irom[0] != plat["irom"][0]:
            warnings.append(f"uvprojx IROM 起址 0x{irom[0]:08X} 已非平台基址 "
                            f"0x{plat['irom'][0]:08X}，且 flash_offset=0x{flash_offset:X}——"
                            "请确认未对同一偏移重复叠加")
        irom = (irom[0] + flash_offset, irom[1] - flash_offset)
        warnings.append(f"flash_offset=0x{flash_offset:X} 已应用："
                        f"FLASH ORIGIN=0x{irom[0]:08X} LENGTH=0x{irom[1]:X}"
                        f"（基址+偏移，容量-偏移）——须与 S5b main.c 的向量表重定位值一致")

    # ---- 启动文件：Keil .s（ARMCC 语法）→ 平台库 GNU 语法同名文件 ----
    gcc_startup = find_gcc_startup(platform_dir, info["keil_startup"])
    if gcc_startup is None:
        warnings.append("未定位到 GNU 语法启动文件（platforms/<platform>/sdk/startup/"
                        "gcc_ride7/）——Makefile 不含启动文件，链接将失败，需用户补")
    else:
        warnings.append(f"Keil 启动文件（ARMCC 语法）已替换为 GNU 语法: "
                        f"{gcc_startup.name}")

    # ---- 链接脚本：工程内用户自维护 .ld > 平台库 linker_scripts/ > 生成 ----
    ld_name = f"{target}.ld"
    ld_path = target_root / ld_name
    linker_generated = False
    existing_ld = None
    for p in sorted(target_root.rglob("*.ld")):
        if not ({q.lower() for q in p.relative_to(target_root).parts[:-1]}
                & PROJECT_DISCOVER_EXCLUDE):
            existing_ld = p
            break
    plat_ld: Path | None = None
    if platform_dir is not None and (platform_dir / "linker_scripts").is_dir():
        plat_lds = sorted((platform_dir / "linker_scripts").glob("*.ld"))
        if plat_lds:
            plat_ld = plat_lds[0]

    if existing_ld is not None and not is_generated_file(existing_ld):
        # 工程内用户自维护脚本：最高优先级（用户显式覆盖平台布局）
        ld_rel = _rel_posix(existing_ld, target_root)
        warnings.append(f"引用工程内已有链接脚本: {ld_rel}")
    elif plat_ld is not None and not flash_offset:
        # 平台库链接脚本（芯片级权威资产）：零偏移场景直接引用
        ld_rel = plat_ld.as_posix()
        warnings.append(f"引用平台库链接脚本: {ld_rel}")
        if existing_ld is not None and is_generated_file(existing_ld):
            # 旧的本 skill 生成脚本已被平台脚本取代 → 清理，避免残留误导
            try:
                existing_ld.unlink()
                warnings.append(f"已移除被平台脚本取代的生成链接脚本: "
                                f"{existing_ld.name}")
            except OSError:
                pass
    else:
        if plat_ld is not None and flash_offset:
            warnings.append(
                f"平台库链接脚本 {plat_ld.name} 未直接引用（flash_offset="
                f"0x{flash_offset:X} 需偏移后的脚本）——改为生成工程内链接脚本")
        if existing_ld is not None:
            # 本 skill 生成的 .ld（含标记）→ 按最新模板重新生成（拾取模板修正）
            _write_if_allowed(existing_ld, render_linker_script(
                target, cpu, irom, iram), warnings, "链接脚本")
            ld_rel = _rel_posix(existing_ld, target_root)
        else:
            _write_if_allowed(ld_path, render_linker_script(
                target, cpu, irom, iram), warnings, "链接脚本")
            ld_rel = ld_name
        linker_generated = True

    # ---- Makefile ----
    makefile_path = target_root / "Makefile"
    makefile_generated = _write_if_allowed(
        makefile_path,
        render_makefile(target, cpu, info["defines"], info["includes"],
                        info["c_sources"], gcc_startup, ld_rel, source_basis),
        warnings, "Makefile")

    return {"makefile_generated": makefile_generated,
            "linker_script_generated": linker_generated,
            "target": target, "warnings": warnings,
            "sources": info["c_sources"]}


def is_generated_file(path: Path) -> bool:
    """判定文件是否为本 skill 生成（首行含生成标记）——决定可否覆盖重新生成。"""
    try:
        first = path.read_text(encoding="utf-8",
                               errors="replace").splitlines()[0]
    except (OSError, IndexError):
        return False
    return GENERATED_MARKER in first


def _contains(parent: Path, child: Path) -> bool:
    try:
        child.resolve().relative_to(parent.resolve())
        return True
    except ValueError:
        return False


def _write_if_allowed(path: Path, content: str, warnings: list[str],
                      label: str) -> bool:
    """skip-if-modified 写入：已存在的用户自维护文件（无生成标记）不覆盖。"""
    if path.is_file():
        first = ""
        try:
            first = path.read_text(encoding="utf-8", errors="replace").splitlines()[0]
        except (OSError, IndexError):
            first = ""
        if GENERATED_MARKER in first:
            path.write_text(content, encoding="utf-8", newline="\n")
            warnings.append(f"{label} 为 S7b 生成文件，已重新生成: {path.name}")
            return True
